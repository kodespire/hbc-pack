#!/bin/sh
# Regenerates native/hbcpack_symbols.h: a #define for every global symbol of the bundled zstd
# decompressor and brotli decoder (deps/), prefixed with hbcpack__, so the library links next to
# other copies of zstd/brotli in the same app. Run after updating deps/.
set -e
cd "$(dirname "$0")/.."
T=$(mktemp -d)
for f in deps/zstd/lib/common/*.c deps/zstd/lib/decompress/*.c deps/brotli/c/common/*.c deps/brotli/c/dec/*.c; do
  clang -std=c11 -O1 -DZSTD_LEGACY_SUPPORT=0 -DZSTD_DISABLE_ASM -DZSTD_NO_TRACE -DXXH_NAMESPACE=ZSTD_ -DZSTD_MULTITHREAD=0 \
    -Ideps/zstd/lib -Ideps/zstd/lib/common -Ideps/brotli/c/include -c "$f" -o "$T/$(echo "$f" | tr / _).o"
done
{
  echo '/* Generated by native/gen-symbols.sh: renames every global symbol of the bundled zstd decompressor and'
  echo ' * brotli decoder so this library can be linked into an app next to @kodespire/zstd-js and'
  echo ' * @kodespire/brotli-js, which carry their own copies. Force-included into every C file (-include). */'
  echo '#ifndef HBCPACK_SYMBOLS_H'
  echo '#define HBCPACK_SYMBOLS_H'
  nm -gU "$T"/*.o | awk '$2 ~ /^[TDBSR]$/ {print $3}' | sed 's/^_//' | sort -u | while read -r s; do echo "#define $s hbcpack__$s"; done
  echo '#endif'
} > native/hbcpack_symbols.h
rm -rf "$T"
echo "wrote native/hbcpack_symbols.h ($(grep -c '^#define [A-Za-z]' native/hbcpack_symbols.h) symbols)"
