#!/usr/bin/env node
// Generates native/hbcpack_opcodes.h from ref/opcodes.json: per opcode the operand widths, the
// operand stream index (same numbering as FORMAT.md streams 32-47), the property-cache operand
// positions and the switch kind. Run: node native/gen-opcodes-h.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const HERE = path.dirname(new URL(import.meta.url).pathname);
const json = JSON.parse(readFileSync(path.join(HERE, '../ref/opcodes.json'), 'utf8'));
const list = Array.isArray(json) ? json : json.opcodes;
const STREAMS = ['reg8', 'reg32', 'u8', 'u16', 'u32', 'str8', 'str16', 'str32', 'fn16', 'fn32', 'bi16', 'bi32', 'addr8', 'addr32', 'imm32', 'dbl64'];
const CLASS_OF = { register: 'reg', uint: 'u', string_id: 'str', function_id: 'fn', bigint_id: 'bi', jump_offset: 'addr', immediate: 'imm', double: 'dbl' };
const SIZE = { Reg8: 1, Reg32: 4, UInt8: 1, UInt16: 2, UInt32: 4, Addr8: 1, Addr32: 4, Imm32: 4, Double: 8 };

const rows = new Array(256).fill(null);
let maxOperands = 0;
for (const op of list) {
  const operands = op.operands.map((o) => ({ size: o.size ?? SIZE[o.type], stream: STREAMS.indexOf(`${CLASS_OF[o.semantic]}${(o.size ?? SIZE[o.type]) * 8}`), semantic: o.semantic }));
  if (operands.some((o) => o.stream < 0)) throw new Error(`${op.name}: unknown operand class`);
  const si = operands.findIndex((o) => o.semantic === 'string_id');
  const ci = operands.findIndex((o) => o.semantic === 'uint' && o.size === 1);
  const cache = si >= 0 && ci >= 0 && /ById/.test(op.name);
  rows[op.opcode] = { name: op.name, operands, cacheSi: cache ? si : -1, cacheCi: cache ? ci : -1, cacheWrite: cache && /Put|Define/.test(op.name) ? 1 : 0,
    sw: op.name === 'UIntSwitchImm' ? 1 : op.name === 'StringSwitchImm' ? 2 : 0 };
  maxOperands = Math.max(maxOperands, operands.length);
}
const lines = [
  '/* Generated by native/gen-opcodes-h.mjs from ref/opcodes.json (HBC version 98). Do not edit. */',
  '#ifndef HBCPACK_OPCODES_H', '#define HBCPACK_OPCODES_H', '#include <stdint.h>', '',
  `#define HBCPACK_MAX_OPERANDS ${maxOperands}`,
  '#define HBCPACK_NUM_OPERAND_STREAMS 16',
  '/* Operand stream indices (FORMAT.md streams 32-47): ' + STREAMS.map((s, i) => `${i}=${s}`).join(' ') + ' */',
  '',
  'typedef struct {',
  '  const char *name;      /* NULL for unassigned opcodes */',
  '  uint8_t n;             /* operand count */',
  `  uint8_t width[${maxOperands}];   /* bytes per operand */`,
  `  int8_t stream[${maxOperands}];   /* operand stream index */`,
  '  int8_t cache_si;       /* string-id operand index for property-cache ops, else -1 */',
  '  int8_t cache_ci;       /* cache-index operand index, else -1 */',
  '  uint8_t cache_write;   /* 1 = write cache (Put/Define) */',
  '  uint8_t sw;            /* 0 none, 1 UIntSwitchImm, 2 StringSwitchImm */',
  '} hbcpack_opcode;',
  '',
  'static const hbcpack_opcode HBCPACK_OPCODES[256] = {',
];
for (let i = 0; i < 256; i++) {
  const r = rows[i];
  if (!r) { lines.push(`  /* ${i} */ { NULL, 0, {0}, {0}, -1, -1, 0, 0 },`); continue; }
  const pad = (arr, fill) => Array.from({ length: maxOperands }, (_, k) => arr[k] ?? fill).join(', ');
  lines.push(`  /* ${i} */ { "${r.name}", ${r.operands.length}, {${pad(r.operands.map((o) => o.size), 0)}}, {${pad(r.operands.map((o) => o.stream), -1)}}, ${r.cacheSi}, ${r.cacheCi}, ${r.cacheWrite}, ${r.sw} },`);
}
lines.push('};', '', '#endif', '');
writeFileSync(path.join(HERE, 'hbcpack_opcodes.h'), lines.join('\n'));
console.log(`wrote hbcpack_opcodes.h: ${list.length} opcodes, max ${maxOperands} operands`);
