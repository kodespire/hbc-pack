// Runs after `npm install`. Replaces the file:../.. link to the repo with the package as npm
// would publish it (`npm pack` of the repo root), so the app builds from the published files
// and autolinking sees exactly what users get. Also writes the test fixtures the self-test
// needs as a JS module (React Native has no file system API).
import { execFileSync } from 'node:child_process';
import { existsSync, lstatSync, mkdirSync, mkdtempSync, readFileSync, rmSync, unlinkSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const app = join(dirname(fileURLToPath(import.meta.url)), '..');
const repo = join(app, '..', '..');

const tmp = mkdtempSync(join(tmpdir(), 'hbc-pack-pack-'));
try {
  const packed = JSON.parse(execFileSync('npm', ['pack', '--json', '--pack-destination', tmp], { cwd: repo, encoding: 'utf8' }));
  const tarball = join(tmp, packed[0].filename);
  const target = join(app, 'node_modules', '@kodespire', 'hbc-pack');
  if (existsSync(target) && lstatSync(target).isSymbolicLink()) unlinkSync(target);
  else rmSync(target, { recursive: true, force: true });
  mkdirSync(target, { recursive: true });
  // -m: do not restore the tarball's fixed 1985 mtimes, or incremental native builds (ninja,
  // CMake) would treat the previous build's objects as current and ship stale code.
  execFileSync('tar', ['-xzmf', tarball, '-C', target, '--strip-components=1']);
  console.log(`installed ${packed[0].filename} (${packed[0].entryCount} files, ${packed[0].size} bytes packed)`);
} finally {
  rmSync(tmp, { recursive: true, force: true });
}

// hello.*: the fixture program; hello2.*: its "next release" (plain and delta containers against hello.*).
const fixtures = ['hello.json'];
for (const v of ['v94', 'v96', 'v98', 'v99']) fixtures.push(`hello.${v}.hbc`, `hello.${v}.hbcp`, `hello2.${v}.hbc`, `hello2.${v}.hbcp`, `hello2.${v}.delta.hbcp`);
const entries = fixtures.map((name) => `  ${JSON.stringify(name)}: ${JSON.stringify(readFileSync(join(repo, 'fixtures', name)).toString('base64'))},`);
writeFileSync(join(app, 'selftest', 'fixtures.generated.js'), `// Generated by scripts/prepare.mjs from ../fixtures (base64). Do not edit.\nexport default {\n${entries.join('\n')}\n};\n`);
